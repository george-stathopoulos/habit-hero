import assert from 'node:assert/strict';
import worker from '../cloudflare/worker.mjs';
import {idTokenClaims} from '../cloudflare/google-auth.mjs';
const base='https://habit-hero-cloudflare.george-stathopoulos.workers.dev';
const assets={fetch:async()=>new Response('assets')};
const headers={'cache-control':'no-store'};
let r=await worker.fetch(new Request(base+'/api/auth/google/start'),{ASSETS:assets});
assert.equal(r.status,503,'missing credentials fail closed');
r=await worker.fetch(new Request(base+'/api/auth/me'),{ASSETS:assets});
assert.equal(r.status,503,'missing database fail closed');
r=await worker.fetch(new Request(base+'/api/auth/google/callback?code=abc&state=bad'),{ASSETS:assets,DB:{},GOOGLE_CLIENT_ID:'id',GOOGLE_CLIENT_SECRET:'secret'});
assert.equal(r.status,401,'missing valid flow fails closed');
r=await worker.fetch(new Request(base+'/api/auth/logout',{method:'POST'}),{ASSETS:assets,DB:{}});
assert.equal(r.status,403,'logout rejects requests without matching Origin');
r=await worker.fetch(new Request(base+'/api/auth/logout',{method:'POST',headers:{Origin:base}}),{ASSETS:assets,DB:{}});
assert.equal(r.status,200);
assert.match(r.headers.get('set-cookie'),/HttpOnly; Secure; SameSite=Lax/);
let captured;
const db={prepare:(sql)=>({bind:(...vals)=>({run:async()=>{captured={sql,vals};return{meta:{changes:1}};}})})};
const env={ASSETS:assets,DB:db,GOOGLE_CLIENT_ID:'public-client-id',GOOGLE_CLIENT_SECRET:'secret'};
r=await worker.fetch(new Request(base+'/api/auth/google/start'),env);
assert.equal(r.status,302);
assert.equal(captured.vals.length,6);
assert.ok(captured.vals[1].length>40 && captured.vals[1]!==captured.vals[2]);
assert.ok(!captured.sql.includes('secret'));
assert.match(r.headers.get('set-cookie'),/__Host-hh_oauth=/);
const authUrl=new URL(r.headers.get('location'));
assert.equal(authUrl.origin,'https://accounts.google.com');
assert.equal(authUrl.searchParams.get('redirect_uri'),base+'/api/auth/google/callback');
assert.equal(authUrl.searchParams.get('code_challenge_method'),'S256');
assert.equal(authUrl.searchParams.get('scope'),'openid email profile');
assert.equal(authUrl.searchParams.get('client_secret'),null);
r=await worker.fetch(new Request(base+'/api/auth/me'),env);
assert.equal(r.status,401);
r=await worker.fetch(new Request(base+'/api/children'),env);
assert.equal(r.status,503,'unfinished child API stays closed');
// Invalid token must be rejected before any remote JWK lookup.
await assert.rejects(()=>idTokenClaims('not.a.valid.jwt','client','nonce'));
console.log('PASS OIDC start, PKCE, secure cookie, unauthenticated access and safe defaults');
